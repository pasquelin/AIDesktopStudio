/** The rank a scenario answers to — `batterie.test.ts` holds every name to this shape. */
export const rankOf = (name: string): string => name.split(' ')[0] ?? ''

// `Object.keys` widens to `string[]`; the table's own type is what says these are action names.
const listed = (): readonly ActionName[] => Object.keys(COVERAGE) as ActionName[]

export const coveredActions = (): readonly ActionName[] =>
  listed().filter(name => COVERAGE[name].length > 0)

export const uncoveredActions = (): readonly ActionName[] =>
  listed().filter(name => COVERAGE[name].length === 0)
